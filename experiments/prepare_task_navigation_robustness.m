function prepared=prepare_task_navigation_robustness(output_dir)
%PREPARE_TASK_NAVIGATION_ROBUSTNESS Freeze all cases before any new IK search.
    if nargin<1,output_dir=fullfile('results','task_navigation_robustness_20261111');end
    if ~isfolder(output_dir),mkdir(output_dir);end
    definitions=task_navigation_robustness_cases();
    sources=struct('cases',fileread(which('task_navigation_robustness_cases')), ...
        'setup',fileread(which('task_navigation_robustness_setup')), ...
        'pool',fileread(which('main_task_navigation_setup')));
    robot=robot_config();robot.manipulator=task_manipulation_config(robot);
    signature=build_struct_signature(struct('definitions',definitions,'sources',sources,'robot',robot));
    prepared_file=fullfile(output_dir,'batch_setup.mat');
    if isfile(prepared_file)
        loaded=load(prepared_file,'prepared');prepared=loaded.prepared;
        assert(strcmp(prepared.signature,signature),'Robustness:FrozenInputsChanged','Use a new output directory after changing frozen inputs.');
        return;
    end
    write_json(fullfile(output_dir,'scenario_definitions.json'),definitions);
    write_json(fullfile(output_dir,'frozen_robot.json'),robot);
    setups=cell(1,numel(definitions));manifest=cell(numel(definitions),10);
    for layout=0:2
        indices=find([definitions.layout_id]==layout);
        reference=task_navigation_robustness_setup(definitions(indices(1)));
        for index=reshape(indices,1,[])
            def=definitions(index);setup=task_navigation_robustness_setup(def,reference);
            assert(strcmp(build_struct_signature(setup.robot),build_struct_signature(robot)));
            setups{index}=setup;relative=fullfile('cases',def.case_id);
            case_dir=fullfile(output_dir,relative);if ~isfolder(case_dir),mkdir(case_dir);end
            write_json(fullfile(case_dir,'case_definition.json'),def);
            write_frozen_scene(setup,case_dir);
            write_json(fullfile(case_dir,'frozen_case_metadata.json'),struct('case_id',def.case_id, ...
                'robot_signature',build_struct_signature(robot),'reference_pool_signature',setup.reference_pool_signature, ...
                'candidate_count',numel(setup.pool),'target_count',setup.scene.num_tasks, ...
                'geometry_pool_scope',setup.geometry_pool_scope));
            manifest(index,:)={def.case_id,def.layout_id,def.distribution_id,2026, ...
                strrep(relative,'\','/'),setup.scene.num_tasks,numel(setup.pool), ...
                def.layout_label,def.distribution_label,setup.reference_pool_signature};
            fprintf('FROZEN %s: %d tasks, %d shared-layout candidates\n',def.case_id,setup.scene.num_tasks,numel(setup.pool));
        end
    end
    writetable(cell2table(manifest,'VariableNames',{'case_id','layout_id','distribution_id','seed','relative_dir', ...
        'target_count','candidate_count','layout_label','distribution_label','reference_pool_signature'}), ...
        fullfile(output_dir,'scenario_manifest.csv'));
    metadata=struct('experiment_id','task_navigation_robustness_20261111','pre_experiment_backup_commit','fee9967', ...
        'signature',signature,'scenario_count',9,'task_modes',{{'position_only','top_down_grasp','table_wipe'}}, ...
        'raw_methods',{{'staged','minimum_seed','reorder_only','joint_local'}}, ...
        'primary_methods',{{'minimum_seed','reorder_only','joint_local'}}, ...
        'primary_staged_label','staged plus common regional minimum-cover repair', ...
        'planned_raw_rows',108,'planned_primary_rows',81,'task_count_each',36,'table_count_each',16, ...
        'robot_signature',build_struct_signature(robot),'deterministic_factorial_not_iid_samples',true, ...
        'tie_tolerance_abs_J',1e-7,'representative_case_id','L0_D2', ...
        'navigation_cost_definition','J=L+0.15*sum(abs(wrapped service-endpoint yaw differences))', ...
        'global_optimal',false,'failure_cases_retained',true,'layout_workers',3,'compute_threads_per_worker',1, ...
        'cache_scope','witness buckets within each layout/mode; counters reset for every library; exact negatives only', ...
        'primary_pair_eligibility','all three primary methods valid, 36 verified tasks and the same regional minimum dock count', ...
        'local_search_budget',setups{1}.planner.strategy.joint_local);
    prepared=struct('definitions',definitions,'setups',{setups},'metadata',metadata,'signature',signature);
    save(prepared_file,'prepared','-v7');write_json(fullfile(output_dir,'metadata.json'),metadata);
    % Existing D0/main support is reusable only because its complete signed
    % inputs still match; the builder independently checks this on replay.
    original=fullfile('results','main_joint_task_navigation_20261111');
    target=fullfile(output_dir,'cases','L0_D0');copied={};
    if isfolder(original)
        names={'main_library_geometry_signature.json'};
        for mode={'position_only','top_down_grasp','table_wipe'}
            m=mode{1};names=[names,{['candidate_library_' m '.mat'],['pair_support_' m '.csv'], ...
                ['candidate_support_' m '.csv'],['ik_cache_' m '.json']}]; %#ok<AGROW>
        end
        for k=1:numel(names)
            source=fullfile(original,names{k});assert(isfile(source),'Robustness:ReferenceArtifactMissing','Reference artifact missing.');
            copyfile(source,fullfile(target,names{k}));copied{end+1}=names{k}; %#ok<AGROW>
        end
    end
    write_json(fullfile(target,'reference_library_reuse.json'),struct('source_directory',original, ...
        'copied_files',{copied},'signed_inputs_rechecked_before_reuse',true,'replay_is_new_ik_validation',false));
    write_json(fullfile(output_dir,'run_state.json'),struct('status','PREPARED','scenario_count',9, ...
        'completed_scenarios',0,'planned_primary_rows',81,'completed_rows',0));
end

function write_frozen_scene(setup,folder)
    scene=setup.scene;cfg=scene.scene_cfg;robot=setup.robot;planner=setup.planner;
    geometry_signature=build_struct_signature(struct('scene_cfg',setup.source_scene_cfg,'pool',setup.pool, ...
        'robot',robot,'nav',build_path_cache_signature(scene.grid_map,scene.map_info,planner), ...
        'routing',planner.routing,'matrix_revision','directional_dense_20261111_v2'));
    metadata=struct('geometry_signature',geometry_signature,'case_id',setup.case_definition.case_id, ...
        'case_definition',setup.case_definition,'source_scene_config',setup.source_scene_cfg, ...
        'reference_scene_config',setup.reference_scene_cfg,'reference_pool_signature',setup.reference_pool_signature, ...
        'geometry_pool_scope',setup.geometry_pool_scope,'robot_signature',build_struct_signature(robot), ...
        'model_revision',robot.manipulator.model.revision,'robot_footprint',robot.footprint, ...
        'task_count',scene.num_tasks,'candidate_count',numel(setup.pool),'table_count',numel(setup.regions), ...
        'mode_order',{setup.mode_order},'methods',{{'staged','minimum_seed','reorder_only','joint_local'}}, ...
        'lambda_theta_m_per_rad',planner.edge_cost.lambda_theta,'preparation_only',true, ...
        'scene',struct('table_centers',cfg.table_positions,'table_orientations_rad',cfg.table_orientations, ...
            'table_length_m',cfg.table.length,'table_width_m',cfg.table.width,'table_height_m',cfg.table.height, ...
            'map_width_m',cfg.map_width_m,'map_height_m',cfg.map_height_m,'start_pose',scene.start_pose, ...
            'border_thickness_m',cfg.border_thickness_m));
    write_json(fullfile(folder,'metadata.json'),metadata);
    writetable(setup.dense_mapping,fullfile(folder,'dense_to_subpool.csv'));
    writetable(setup.table_counts,fullfile(folder,'table_candidate_counts.csv'));
    tasks=table([scene.tasks.id]',[scene.tasks.table_id]',[scene.tasks.x]',[scene.tasks.y]',[scene.tasks.z]', ...
        'VariableNames',{'task_id','table_id','x_m','y_m','z_m'});writetable(tasks,fullfile(folder,'tasks.csv'));
    P=reshape([setup.pool.pose],3,[])';N=numel(setup.pool);
    pool=table((2:N+1)',[setup.pool.candidate_id]',[setup.pool.dense_candidate_id]', ...
        [setup.pool.table_id]',[setup.pool.side_id]',P(:,1),P(:,2),P(:,3), ...
        'VariableNames',{'node_index','candidate_id','dense_candidate_id','table_id','side_id','x_m','y_m','yaw_rad'});
    writetable(pool,fullfile(folder,'candidate_pool.csv'));
end

function write_json(path,value)
    fid=fopen(path,'w','n','UTF-8');assert(fid>=0);cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
    fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));
end
