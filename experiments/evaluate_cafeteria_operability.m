function operability = evaluate_cafeteria_operability(scene, robot_cfg)
%EVALUATE_CAFETERIA_OPERABILITY Apply existing reachability gates per task.

    template = struct('task_id', 0, 'table_id', 0, 'robot_profile', '', ...
        'arm_base_z', 0, 'task_z', 0, 'relative_z', 0, 'reach_z_max', 0, ...
        'reachability_score', 0, 'reachability_result', '', 'model_feasible', false);
    operability = repmat(template, scene.num_tasks, 1);
    fprintf('===== CAFETERIA OPERABILITY GATE =====\n');
    for i = 1:scene.num_tasks
        task = scene.tasks(i);
        relative_z = task.z - robot_cfg.arm_base_mount_z;
        vertical_feasible = relative_z >= robot_cfg.single_arm.reach_z_min && ...
            relative_z <= robot_cfg.single_arm.reach_z_max;
        score = NaN;
        result = 'PASS_VERTICAL_GEOMETRY';
        if ~vertical_feasible
            result = 'TASK_GEOMETRY_REACH_LIMIT';
        end
        operability(i) = struct('task_id', i, 'table_id', task.table_id, ...
            'robot_profile', robot_cfg.geometry_profile, ...
            'arm_base_z', robot_cfg.arm_base_mount_z, 'task_z', task.z, ...
            'relative_z', relative_z, ...
            'reach_z_max', robot_cfg.single_arm.reach_z_max, ...
            'reachability_score', score, 'reachability_result', result, ...
            'model_feasible', vertical_feasible);
        fprintf(['T%d: robot_profile=%s arm_base_z=%.3f task_z=%.3f ' ...
            'relative_z=%.3f reach_z_max=%.3f reachability=%s\n'], ...
            task.table_id, robot_cfg.geometry_profile, robot_cfg.arm_base_mount_z, ...
            task.z, task.z - robot_cfg.arm_base_mount_z, ...
            robot_cfg.single_arm.reach_z_max, result);
    end
    fprintf('=======================================\n');
end
