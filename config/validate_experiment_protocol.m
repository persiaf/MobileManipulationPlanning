function validate_experiment_protocol(cfg)
%VALIDATE_EXPERIMENT_PROTOCOL Reject drift in a formal paired experiment.
    if ~isfield(cfg,'experiment_protocol') || ~isfield(cfg.experiment_protocol,'enforce') || ...
            ~cfg.experiment_protocol.enforce, return; end
    standard = experiment_protocol_config();
    validate_main_robot_config(cfg.robot_cfg);
    threshold=cfg.reachability.threshold;
    if ~isnumeric(threshold) || ~isscalar(threshold) || ~isfinite(threshold) || ...
            abs(threshold-standard.reachability_threshold)>1e-12 || ...
            ~strcmpi(cfg.reachability.mode,standard.reachability_mode) || ...
            ~isequal(cfg.execution.return_to_start,true) || ...
            ~isequal(cfg.benchmark.include_return_to_start,true) || ...
            ~strcmpi(cfg.benchmark.order_mode,'fixed_order')
        error('validate_experiment_protocol:ConflictingSetting', ...
            'Formal comparisons require the main score threshold, nominal reachability and a shared return-to-start condition.');
    end
end
