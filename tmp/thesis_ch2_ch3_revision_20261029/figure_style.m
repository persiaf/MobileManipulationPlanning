function figure_style()
set(groot,'defaultFigureVisible','off','defaultFigureColor','w', ...
    'defaultAxesFontName','Times New Roman','defaultAxesFontSize',10.5, ...
    'defaultTextFontName','SimSun','defaultTextFontSize',10.5, ...
    'defaultAxesLineWidth',0.75,'defaultLineLineWidth',1.2);
end
