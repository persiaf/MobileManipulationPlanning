h(3,'3.2.2 面向任务的候选朝向展开')
p(r'对于同一个候选位置，仅采用面向任务质心的朝向可能忽略桌角或稀疏分布的任务。本文同时考虑面向桌边内法向、任务质心、各个任务点和桌面中心的基础朝向。设目标参考点为 $\boldsymbol v$，候选位置为 $\boldsymbol x_k$，相应基础朝向由指向向量计算：')
e(r'\theta^{(0)}(\boldsymbol x_k,\boldsymbol v)=\operatorname{atan2}(v_y-y_k,v_x-x_k).')
p(r'当参考点与候选位置过于接近时，不从该向量生成方向。对于其余基础朝向，先将角度归一化到主值区间，并以 4° 为角度容差去除重复方向，再叠加有限角度扰动。默认扰动集合为')
e(r'\Delta\Theta=\{-\pi/6,-\pi/12,0,\pi/12,\pi/6\},\qquad\theta_k=\operatorname{wrap}(\theta^{(0)}+\delta),\quad\delta\in\Delta\Theta.')
p(r'这里的扰动用于扩展候选搜索方向，而非描述实际停靠误差。两者虽然都包含角度偏移，但作用不同：候选方向扰动改变可供选择的名义位姿，停靠误差扰动则检验既定位姿附近的可达性变化。对生成的位姿，按 0.01 m 的位置容差、2° 的航向容差以及相同桌边编号进行去重，保留确定的生成顺序。')
p(r'方向展开会同时改变机械臂基座在世界坐标系中的位置和任务点在机械臂局部坐标中的方向。因此，不能先对位置计算一次可达性，再把该结果复制到所有朝向。每个去重后的完整位姿均需单独执行底盘碰撞检查与任务评分。采样分辨率也会影响最终候选集合：某个任务没有可覆盖候选，只能说明当前离散集合未提供支持，不能直接推断连续空间中不存在可行停靠位姿。')

h(2,'3.3 底盘几何可行性筛选')
h(3,'3.3.1 矩形轮廓与占据栅格相交检测')
p(r'停靠状态下底盘仍占据有限面积，不能简化为单个栅格中心。本文以长度 0.423 m、宽度 0.366 m 的矩形表示底盘水平轮廓，其中长度方向对应机器人局部前向轴，宽度方向对应左向轴。设变换后的底盘轮廓为 $\mathcal F(p_k)$，占据栅格构成的障碍区域为 $\mathcal O_g$，地图有效区域为 $\mathcal D$，几何筛选要求')
e(r'\mathcal F(p_k)\cap\mathcal O_g=\varnothing,\qquad\mathcal F(p_k)\subset\operatorname{int}(\mathcal D).')
p(r'占据栅格按具有真实面积的正方形处理。碰撞检测先计算旋转矩形的轴对齐包围盒，再提取附近占据栅格，最后通过分离轴判据检验矩形与各个栅格正方形是否相交。该过程既考虑栅格边长，也考虑底盘姿态，能够避免仅检测底盘四角或仅检测障碍物中心引起的漏检。')
p(r'这里的障碍集合对应场景构建后的占据地图，已经包含栅格化安全带。当前场景的安全带参数与地图分辨率均为 0.05 m，地图生成时通过八邻域扩展占据掩码；因此，它是离散栅格上的扩展区域，不能直接等同于精确的圆盘形欧氏膨胀。随后计算的轮廓间隙，也是相对这一扩展后地图的间隙。')
p(r'令底盘半长、半宽分别为 $a_B$、$b_B$，栅格半边长为 $h_g$；某占据栅格中心与底盘中心的差为 $(\Delta x,\Delta y)$，并记 $c=\cos\theta_k$、$s=\sin\theta_k$。两个形状相交当且仅当下列四个投影区间均发生重叠：')
e(r'\begin{aligned}|\Delta x|&\le a_B|c|+b_B|s|+h_g,\\|\Delta y|&\le a_B|s|+b_B|c|+h_g,\\|\Delta xc+\Delta ys|&\le a_B+h_g(|c|+|s|),\\|-\Delta xs+\Delta yc|&\le b_B+h_g(|c|+|s|).\end{aligned}')
p(r'实现中在比较时加入很小的数值容差，并将相切视为碰撞；底盘接触地图边界同样被排除。筛选所保证的是底盘轮廓相对离散占据地图的无碰，而非机械臂伸展过程中的全身无碰。桌面在底盘导航平面中表现为不可穿越的投影障碍，机械臂跨越桌边完成操作的空间关系仍需由独立的机械臂碰撞模型进一步验证。')

h(3,'3.3.2 轮廓间隙与候选任务对预筛')
p(r'对于无碰候选，进一步计算底盘边缘与占据栅格及地图边界之间的最小间隙，用于比较停靠安全裕量：')
e(r'd_{\mathrm{clr}}(p_k)=\min\left\{\operatorname{dist}(\mathcal F(p_k),\mathcal O_g),\operatorname{dist}(\mathcal F(p_k),\partial\mathcal D)\right\}.')
p(r'距离通过两类顶点到边的最短距离获得，即底盘顶点到栅格边，以及栅格顶点到底盘边。该量是轮廓之间的间隔，不能用底盘中心到障碍物的距离代替。当前几何筛选要求不接触障碍，综合代价中的 0.25 m 则是间隙评价的归一化尺度，并未作为所有候选必须满足的硬间隙。二者分别承担可行性剔除和候选质量区分的作用。')
p(r'在底盘通过筛选后，可以对候选与任务的组合启用快速预筛。预筛复用单臂模型中的水平半径、高度、后向范围和侧向范围硬条件，只有左右两臂均不能通过这些条件时才直接排除该组合。它不近似最终评分，也不改变通过预筛的组合所采用的正式评价公式。因此，在名义评价下，预筛的目标是跳过确定得分为零的计算，而不是以经验距离阈值替代双臂模型。默认流程关闭该开关，实验对比时应单独记录其开启状态。')

h(2,'3.4 单机械臂可达性评价')
h(3,'3.4.1 任务相对机械臂基座的位置描述')
p(r'左右机械臂基座在底盘局部坐标系中的前向偏移相同，横向偏移符号相反。设前向偏移 $d_x=0.2115\,\mathrm m$，双臂基座间距 $d_a=0.250\,\mathrm m$，机械臂安装高度 $z_A=0.1833\,\mathrm m$，并以 $\varepsilon_L=1$、$\varepsilon_R=-1$ 区分左右臂，则第 $\ell$ 臂基座的平面世界坐标为')
e(r'\boldsymbol a_\ell^W(p_k)=\begin{bmatrix}x_k\\y_k\end{bmatrix}+\boldsymbol R_2(\theta_k)\begin{bmatrix}d_x\\\varepsilon_\ell d_a/2\end{bmatrix},\qquad\ell\in\{L,R\}.')
p(r'将任务点相对该基座的平面向量旋转至与底盘方向一致的局部坐标，并保留垂向偏移：')
e(r'\begin{bmatrix}u_{i\ell}\\v_{i\ell}\end{bmatrix}=\boldsymbol R_2(-\theta_k)\left(\begin{bmatrix}x_i\\y_i\end{bmatrix}-\boldsymbol a_\ell^W(p_k)\right),\qquad z_{i\ell}=z_i-z_A.')
p(r'其中，$u_{i\ell}$ 和 $v_{i\ell}$ 分别表示任务相对机械臂基座的前向和侧向分量。水平距离定义为')
e(r'r_{i\ell}=\sqrt{u_{i\ell}^{2}+v_{i\ell}^{2}}.')
p(r'上述变换显式保留安装偏置。例如，当底盘绕自身中心旋转时，即使其中心位置不变，两臂基座也会沿以各自安装偏置为半径的轨迹移动。直接利用任务到底盘中心的距离会忽略这一变化，进而误判靠近桌边、桌角或两臂重叠区域的任务。')

h(3,'3.4.2 几何范围约束')
p(r'单臂几何范围由水平环带、相对安装高度区间以及局部方向范围共同限定。令 $H_{i\ell}(p_k)$ 为硬条件指示量，其为 1 的条件为')
e(r'\begin{aligned}R_{\min}&\le r_{i\ell}\le R_{\max},\\z_{\min}&\le z_{i\ell}\le z_{\max},\\u_{i\ell}&\ge-R_{\mathrm{back}},\qquad |v_{i\ell}|\le1.1R_{\mathrm{lat}}.\end{aligned}')
p(r'本章取 $R_{\min}=0.010\,\mathrm m$、$R_{\max}=0.278\,\mathrm m$，相对高度范围为 −0.142～0.334 m，后向范围为 0.197 m，侧向尺度为 0.278 m。前向尺度为 0.278 m，参与后续方向评分；由于水平距离上界已限制前向分量，不再另加重复的前向上界。允许一定后向范围，是为了保留机械臂折叠后可能覆盖的侧后方位置，而非要求所有任务必须位于底盘正前方。')
p(r'这些条件描述的是用于规划的近似工作区域，不能由其反推出每个点均存在满足全部关节约束的解。当任务超出任一硬范围时，单臂评分直接置零；通过硬范围仅表明值得继续评价，仍需由连续评分区分临近边界和位于较适中操作区域的任务。')

h(3,'3.4.3 连续评分与阈值判定')
p(r'为兼顾距离余量、适中操作距离、垂向余量和方向偏好，定义五个无量纲分量。令 $r_c=(R_{\min}+R_{\max})/2$、$z_c=(z_{\min}+z_{\max})/2$，并以 $\operatorname{clip}_{[0,1]}$ 表示截断到单位区间，有')
e(r'\begin{aligned}s_d&=1-r_{i\ell}/R_{\max},\\s_c&=\max\{0,1-|r_{i\ell}-r_c|/[(R_{\max}-R_{\min})/2]\},\\s_z&=\max\{0,1-|z_{i\ell}-z_c|/[(z_{\max}-z_{\min})/2]\},\\s_f&=\operatorname{clip}_{[0,1]}(u_{i\ell}/R_{\mathrm{front}}),\\s_l&=1-|v_{i\ell}|/R_{\mathrm{lat}}.\end{aligned}')
p(r'距离分量随水平距离增大而降低，中心分量在环带中部达到最大值，两者共同避免将“越靠近基座越好”作为唯一偏好。高度分量在垂向区间中部较高，在上下边界附近降低。前向分量对正前方目标提供奖励，后方目标该项为零，但不会仅因此被剔除；侧向分量则表达过大侧向偏移的不利影响。各分量是工程评价项，不是雅可比可操作度，也没有由它们推导关节力矩或抓取稳定性。')
e(r'\widetilde\rho_\ell(p_k,t_i)=\operatorname{clip}_{[0,1]}\left(0.30s_d+0.25s_c+0.20s_z+0.15s_f+0.10s_l\right).')
p(r'以 $\tau_r=0.30$ 为可达评分阈值，最终单臂评分定义为')
e(r'\rho_\ell(p_k,t_i)=\begin{cases}\widetilde\rho_\ell(p_k,t_i),&H_{i\ell}(p_k)=1\ \text{且}\ \widetilde\rho_\ell(p_k,t_i)\ge\tau_r,\\0,&\text{其他情形}.\end{cases}')
p(r'这一处理将几何约束和质量阈值分开：前者排除明确超出模型范围的任务，后者排除虽然在范围内、综合评分仍偏低的任务。调整阈值会改变覆盖集合，因此不同算法比较必须使用相同阈值，不能通过放宽阈值单独提高某一种方法的覆盖率。本文采用固定权重与阈值，不将其描述为经过真实机械臂成功率标定的参数。')

h(2,'3.5 双臂联合可达性评价')
h(3,'3.5.1 任一单臂可执行任务的联合评分')
p(r'本章主任务由一只机械臂即可完成。对于同一任务，只要左臂或右臂之一达到评分要求，该候选即为任务提供几何支持。联合评分因此采用两臂评分的最大值：')
e(r'\rho(p_k,t_i)=\max\{\rho_L(p_k,t_i),\rho_R(p_k,t_i)\}.')
p(r'建议执行臂取评分较高者；当两臂评分相同时优先选择左臂，两臂均为零时标记不可达：')
e(r'a_i(p_k)=\begin{cases}L,&\rho_L\ge\rho_R\ \text{且}\ \rho>0,\\R,&\rho_R>\rho_L,\\\varnothing,&\rho=0.\end{cases}')
p(r'该规则得到的是逐任务的局部建议，尚未考虑同一停靠点内多任务的左右臂负载均衡、动作先后次序或共享空间冲突。在后续任务分配中，可以在保留可达性约束的前提下进一步调整执行臂。尤其需要区分“左右臂都可完成同一任务”和“两臂同时完成协同任务”：前者是本节的并集关系，后者通常需要同时满足两臂目标位姿、相对位姿和无碰要求，不能用最大值评分替代。')

h(3,'3.5.2 任务覆盖集合与可行关系矩阵')
p(r'对候选 $p_k$，定义其在区域内的任务覆盖集合和覆盖率：')
e(r'\mathcal C_j(p_k)=\{t_i\in\mathcal T_j\mid\rho(p_k,t_i)>0\},\qquad\eta_k=\frac{|\mathcal C_j(p_k)|}{n_j}.')
p(r'由于单臂评分已经经过阈值截断，联合评分大于零与至少一臂达到阈值等价。再定义任务与候选的二值关系矩阵：')
e(r'C_{ik}=\begin{cases}1,&t_i\in\mathcal C_j(p_k),\\0,&t_i\notin\mathcal C_j(p_k).\end{cases}')
p(r'矩阵的行表示任务，列表示候选。列中非零元素的数量反映该候选一次停靠能够覆盖多少任务；行中非零元素的数量反映某个任务具有多少备选停靠支持。若一行全为零，则后续集合覆盖算法无法仅通过调整选择顺序补足该任务，需要检查采样范围、朝向或几何模型。这种表示将操作约束转化为上层组合规划能够直接使用的离散关系，同时保留连续评分用于区分多个可行候选。')
p(r'候选库保存所有通过底盘碰撞检查的位姿，包括没有覆盖任何任务的候选，以便统计原始采样、碰撞筛除和可达性筛除各阶段的数量。用于实际覆盖选择时，应取覆盖集合非空的有效子集。因而“库中候选总数”和“具有任务支撑的候选数”是两个不同指标，实验统计中应分别报告。')

h(3,'3.5.3 离散停靠误差下的几何鲁棒性扩展')
p(r'为考察小范围停靠偏差对覆盖关系的影响，在名义模型之外设置可选的离散扰动评价。给定平移偏移集合与航向偏移集合，组合得到 $M_\delta$ 个扰动样本。对第 $m$ 个样本，直接在世界坐标中叠加平移并对航向归一化：')
e(r'p_k^{(m)}=\left(x_k+\delta x_m,y_k+\delta y_m,\operatorname{wrap}(\theta_k+\delta\theta_m)\right).')
p(r'当前配置采用原点及平面四个轴向的 ±0.02 m 偏移，并与 0、±0.03 rad 航向偏移做笛卡尔积，共形成 15 个样本。分别计算各扰动位姿的双臂联合评分，再统计通过比例：')
e(r'q_{ik}=\frac{1}{M_\delta}\sum_{m=1}^{M_\delta}\mathbf1\!\left[\rho(p_k^{(m)},t_i)\ge\tau_r\right].')
p(r'默认主流程采用名义评分；启用鲁棒模式时，以通过比例构造覆盖集合，并保留原有名义评分供对照。当前配置要求通过比例为 1，即全部离散样本均通过，写为')
e(r'\mathcal C_j^{\mathrm{rob}}(p_k)=\{t_i\in\mathcal T_j\mid q_{ik}\ge q_{\min}\},\qquad q_{\min}=1.')
p(r'上述比例只是给定离散扰动集上的经验覆盖指标。误差幅值为配置边界，尚未由实测停靠误差标定；评价也未检查每个扰动位姿的底盘碰撞或连续扰动集合。因此，全部样本通过不能推出连续误差范围内必然无碰，更不能推出真实系统具有某一概率水平的成功保证。当前鲁棒模式对每个样本允许重新选择评分更高的机械臂，其几何意义是每次偏差下至少有一臂满足要求，而不是固定某只手在全部偏差下都可执行。')

h(2,'3.6 停靠位姿综合评价')
h(3,'3.6.1 覆盖质量与朝向代价')
p(r'通过几何筛选后，不同候选在覆盖数量、操作质量、朝向和间隙方面仍存在差异。本文构造无量纲局部代价，为后续多停靠选择提供排序信息。名义模式下，首先对区域内全部任务的联合评分求平均：')
e(r'\Gamma_k=\frac{1}{n_j}\sum_{t_i\in\mathcal T_j}\rho(p_k,t_i).')
p(r'这里的均值包含不可达任务对应的零值，而不是仅对已覆盖任务求均值。因此，一个仅覆盖少量高评分任务的候选，不能仅凭这些任务的平均值获得过高评价。可达性代价与覆盖代价分别为')
e(r'J_r(p_k)=1-\Gamma_k,\qquad J_c(p_k)=1-\eta_k.')
p(r'两项具有相关性，但关注点不同：覆盖代价只反映阈值以上任务的比例，可达性代价进一步区分这些任务的评分高低。鲁棒模式下，候选的联合评分列改用 $q_{ik}$，故可达性代价对应区域内扰动通过比例的均值，此时不应再将其解释为名义几何评分的均值。')
p(r'朝向代价根据底盘航向与指向区域任务质心方向的偏差计算。令 $\theta_k^\star$ 表示理想朝向，则')
e(r'\theta_k^\star=\operatorname{atan2}(\overline t_{j,y}-y_k,\overline t_{j,x}-x_k),\qquad J_\theta(p_k)=\frac{|\operatorname{wrap}(\theta_k-\theta_k^\star)|}{\pi}.')
p(r'这一代价反映底盘相对任务分布的方向偏好，不是末端执行器姿态误差。候选生成阶段仍保留面向单个任务和桌边法向的朝向，综合评价只为这些方向施加不同权重，不会用质心方向直接覆盖它们的几何评价。')

