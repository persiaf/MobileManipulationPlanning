p(r'接近代价采用候选到局部参考点的欧氏距离近似。参考点取任务质心与桌面中心的中点，并使用区域相关尺度进行归一化：')
e(r'\begin{aligned}\boldsymbol e_j&=(\overline{\boldsymbol t}_j+\boldsymbol c_j)/2,\\D_j&=\max\{\|\boldsymbol c_j-\boldsymbol e_j\|_2+1.5\,\mathrm m,1.0\,\mathrm m\},\\J_a(p_k)&=\min\{1,\|\boldsymbol x_k-\boldsymbol e_j\|_2/D_j\}.\end{aligned}')
p(r'该参考点用于表达候选与区域任务分布的局部距离关系，并非地图中的实际入口，也不等于从机器人起点到候选的无碰路径代价。尤其在桌面或其他障碍阻挡直线段时，欧氏距离只能提供粗略排序，真实导航代价仍需在后续路径规划中计算。')
p(r'机动代价以朝向代价为基础；当区域指定偏好停靠侧且候选位于其他侧时，增加换侧惩罚。令 $I_{\mathrm{side}}$ 表示上述条件是否成立，取惩罚系数 $\lambda_s=0.15$，则')
e(r'J_m(p_k)=\min\{1,J_\theta(p_k)+\lambda_s I_{\mathrm{side}}(p_k)\}.')
p(r'若区域没有指定偏好侧，机动代价与朝向代价相同。该项只是局部启发式，不代表完整的底盘转向时间或侧向移动能耗。在解释权重敏感性时，需要注意两项在这一条件下并非独立指标，增大任意一项权重都会强化面向任务质心的偏好。')

