function tests = test_scene_complexity_experiment_smoke
%TEST_SCENE_COMPLEXITY_EXPERIMENT_SMOKE Tiny schema check for P1 experiment.
    tests = functiontests(localfunctions);
end

function testQuickExperimentSchema(testCase)
    [raw, summary] = exp_scene_complexity_p1(struct('quick_mode', true, ...
        'cases', {{'C0'}}, 'seeds', 2026, 'augmentation_modes', {{'off'}}, ...
        'strategies', {{'bottom_up'}}, 'skip_stage3', true));
    required = {'case_id','augmentation_mode','strategy','map_width','map_height', ...
        'table_count','task_count','region_count','raw_candidate_count', ...
        'collision_valid_candidate_count','reachability_valid_candidate_count', ...
        'final_library_candidate_count','supplementary_candidate_count', ...
        'selected_docking_pose_count','candidate_library_coverage', ...
        'verified_completion','task_path_length','return_path_length', ...
        'total_path_length','T_candidate','T_strategy','T_path_cost', ...
        'T_total','path_cost_query_count','expensive_planner_calls', ...
        'cache_hit','cache_miss','success','failure_reason'};
    verifyTrue(testCase, all(ismember(required, raw.Properties.VariableNames)));
    verifyTrue(testCase, raw.success(1), raw.failure_reason{1});
    verifyGreaterThanOrEqual(testCase, raw.task_count(1), 48);
    verifyGreaterThanOrEqual(testCase, raw.final_library_candidate_count(1), 1);
    verifyGreaterThanOrEqual(testCase, height(summary), 1);
end
