function init_paths(project_root)
    %INIT_PATHS Add all project folders by absolute path.
    %   init_paths() automatically locates the project root from this file.
    %   init_paths(project_root) uses the given root path.
    %
    %   Do not call clear/close/clc here: this function should only manage paths.

    if nargin < 1 || isempty(project_root)
        this_file = mfilename('fullpath');
        pipeline_dir = fileparts(this_file);
        project_root = fileparts(pipeline_dir);
    end

    project_root = char(project_root);
    if ~isfolder(project_root)
        error('init_paths:InvalidRoot', '项目根目录不存在: %s', project_root);
    end

    folders = { ...
        'config', ...
        'environment', ...
        'docking', ...
        'manipulator', ...
        'collision', ...
        'global_planner', ...
        'execution', ...
        'experiments', ...
        'integration', ...
        'calibration', ...
        'planning_strategy', ...
        'tests', ...
        'visualization', ...
        'utils', ...
        'pipeline' ...
    };

    for k = 1:numel(folders)
        folder_path = fullfile(project_root, folders{k});
        if isfolder(folder_path)
            addpath(genpath(folder_path));
        else
            warning('init_paths:MissingFolder', '未找到项目子目录: %s', folder_path);
        end
    end

    rehash;

    % Fail early with a clear message if key functions are not visible.
    required_functions = { ...
        'robot_config', 'scene_config', 'planner_config', ...
        'build_scene', 'validate_scene_config', 'assign_tasks_to_tables', ...
        'build_task_regions', 'stage1_build_scene' ...
    };

    missing = {};
    for k = 1:numel(required_functions)
        if exist(required_functions{k}, 'file') ~= 2
            missing{end+1} = required_functions{k}; %#ok<AGROW>
        end
    end

    if ~isempty(missing)
        error('init_paths:MissingFunction', ...
              ['以下关键函数未加入 MATLAB 路径或文件不存在: %s\n' ...
               '请确认当前运行的是项目根目录下的 main_mobile_manipulation_planning.m，' ...
               '且 environment/validate_scene_config.m 等文件存在。'], ...
              strjoin(missing, ', '));
    end
end
