function plot_framework_pipeline(out_dir)
%PLOT_FRAMEWORK_PIPELINE Draw a clean horizontal RCH-MT-MMP framework.
%
%   Stage numbering is continuous (Stage 1-6) after the scene-input box,
%   with enlarged box text so the figure stays legible when scaled to
%   \textwidth in the two-column IEEEtran layout.

    if nargin < 1 || isempty(out_dir)
        out_dir = fullfile(fileparts(fileparts(mfilename('fullpath'))), ...
                           'results', 'figures');
    end
    if ~exist(out_dir, 'dir'), mkdir(out_dir); end

    fig = figure('Name', 'RCH-MT-MMP Framework', 'Visible', 'off', ...
                 'Color', 'w', 'Position', [80, 80, 1500, 360]);
    ax = axes('Parent', fig, 'Position', [0.015, 0.04, 0.97, 0.92]);
    axis(ax, [0 1 0 1]);
    axis(ax, 'off');
    hold(ax, 'on');

    % {label lines; stage number (0 = no stage label)}
    stages = { ...
        {{'Scene and', 'task input'},             0}; ...
        {{'Task region', 'construction'},         1}; ...
        {{'Docking', 'candidate', 'generation'},  2}; ...
        {{'Reachability', 'evaluation'},          3}; ...
        {{'Multi-docking', 'selection'},          4}; ...
        {{'Global route', 'planning'},            5}; ...
        {{'Execution'},                           6} ...
    };
    colors = [ ...
        0.86 0.92 0.98;
        0.88 0.95 0.88;
        0.99 0.92 0.82;
        0.95 0.88 0.98;
        0.98 0.88 0.88;
        0.88 0.94 0.96;
        0.94 0.94 0.88];

    n = numel(stages);
    box_w = 0.118;
    box_h = 0.44;
    y = 0.40;
    x0 = 0.018;
    gap = (0.964 - n * box_w) / (n - 1);

    box_centers = zeros(n, 2);
    for i = 1:n
        x = x0 + (i - 1) * (box_w + gap);
        rectangle(ax, 'Position', [x, y, box_w, box_h], ...
                  'Curvature', 0.08, 'FaceColor', colors(i, :), ...
                  'EdgeColor', [0.22 0.22 0.22], 'LineWidth', 1.2);
        text(ax, x + box_w / 2, y + box_h / 2, stages{i}{1}, ...
             'HorizontalAlignment', 'center', 'VerticalAlignment', 'middle', ...
             'FontName', 'Times New Roman', 'FontSize', 18, ...
             'FontWeight', 'bold', 'Interpreter', 'none');
        if stages{i}{2} > 0
            text(ax, x + box_w / 2, y - 0.075, ...
                 sprintf('Stage %d', stages{i}{2}), ...
                 'HorizontalAlignment', 'center', ...
                 'FontName', 'Times New Roman', ...
                 'FontSize', 14, 'Color', [0.35 0.35 0.35], ...
                 'Interpreter', 'none');
        end
        box_centers(i, :) = [x + box_w / 2, y + box_h / 2];
    end

    ax_pos = get(ax, 'Position');
    for i = 1:n-1
        x_start = box_centers(i, 1) + box_w / 2 + 0.006;
        x_end = box_centers(i+1, 1) - box_w / 2 - 0.006;
        y_mid = box_centers(i, 2);
        annotation(fig, 'arrow', ...
            ax_pos(1) + ax_pos(3) * [x_start, x_end], ...
            ax_pos(2) + ax_pos(4) * [y_mid, y_mid], ...
            'Color', [0.25 0.25 0.25], 'LineWidth', 1.4, ...
            'HeadWidth', 9, 'HeadLength', 9);
    end

    % PNG (300 dpi) + FIG via the shared helper
    export_pub_figure(fig, fullfile(out_dir, 'fig_framework_pipeline'));
    % Vector PDF (tight bounding box) for direct LaTeX inclusion
    exportgraphics(fig, fullfile(out_dir, 'fig_framework_pipeline.pdf'), ...
                   'ContentType', 'vector');
    close(fig);
end
