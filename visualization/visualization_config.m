function cfg = visualization_config(varargin)
%VISUALIZATION_CONFIG Canonical publication visualization configuration.
%   This copy lives with the visualization implementation. The config-folder
%   entry point has the same contract for legacy path initialization.
    cfg = canonical_config();
    if nargin >= 1 && ~isempty(varargin{1})
        cfg = merge_struct_recursive(cfg, varargin{1});
    end
end

function cfg = canonical_config()
    cfg = struct();
    cfg.show_map = true; cfg.show_regions = true; cfg.show_region_labels = true;
    cfg.show_tables = true; cfg.show_table_orientation = true; cfg.show_tasks = true;
    cfg.show_infeasible_tasks = true; cfg.show_candidates = false; cfg.candidate_stride = 20;
    cfg.show_selected_docks = true; cfg.show_sparse_graph = true; cfg.show_final_route = true;
    cfg.show_static_obstacles = true; cfg.show_start = true; cfg.show_legend = true;
    cfg.show_grid = true; cfg.save_png = true; cfg.save_fig = false;
    cfg.output_dir = fullfile('results', 'figures', 'visualization_report');
    cfg.figure_visible = 'off'; cfg.dpi = 300; cfg.font_size = 9;
    cfg.close_figures_after_save = true;
    cfg.style = struct('name','ieee_robotics','font_name','Arial','font_size',9, ...
        'line_width',1.4,'axis_line_width',0.8,'background',[1 1 1], ...
        'robot',[0.00 0.35 0.65],'table',[0.45 0.45 0.45], ...
        'task',[0.10 0.55 0.20],'dock',[0.85 0.33 0.10], ...
        'path',[0.00 0.20 0.80],'region',[0.35 0.35 0.35], ...
        'obstacle',[0.20 0.20 0.20],'candidate',[0.55 0.55 0.55], ...
        'grid',[0.92 0.92 0.92]);
    cfg.output_names = struct('scene','scene','candidate','candidate', ...
        'docking','docking','planning','planning', ...
        'scene_region','scene_region','sparse_graph','sparse_graph', ...
        'before_event','before_event','event','event','replanning','replanning', ...
        'comparison','comparison');
    cfg.legacy = legacy_defaults();
end

function legacy = legacy_defaults()
    legacy = struct('show_scene',true,'show_candidates',true,'show_docking',true, ...
        'show_global_path',true,'show_reachability',false,'show_task_links',true, ...
        'show_arm_assign',true,'show_cost_heatmap',false,'show_arm_task_links',false, ...
        'show_task_dock_links',false,'show_task_labels',true,'show_dock_labels',true, ...
        'show_arm_workspace',true,'show_dock_coverage_text',true,'show_dense_debug_info',false);
end
