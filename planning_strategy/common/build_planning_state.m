function planning_state = build_planning_state(scene, robot_cfg, planner_cfg, ...
        candidate_library, rc2_plan, task_state, runtime_state)
%BUILD_PLANNING_STATE Package RC2 outputs for deterministic RC3 handoff.
    if nargin < 6 || isempty(task_state), task_state = []; end
    if nargin < 7 || isempty(runtime_state), runtime_state = struct(); end
    planning_state = struct('scene', scene, 'tasks', scene.tasks, ...
        'task_state', task_state, 'robot_cfg', robot_cfg, ...
        'planner_cfg', planner_cfg, 'candidate_library', candidate_library, ...
        'rc2_plan', rc2_plan, 'sparse_graph', rc2_plan.sparse_graph, ...
        'runtime_state', runtime_state);
end
