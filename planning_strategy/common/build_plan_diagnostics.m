function diagnostics = build_plan_diagnostics(diagnostics)
%BUILD_PLAN_DIAGNOSTICS Ensure strategy diagnostics have a stable schema.
% Output fields count edits, route queries and cache behavior for paper
% experiments. Missing values are filled with zero-safe defaults.

    if nargin < 1 || isempty(diagnostics)
        diagnostics = struct();
    end
    defaults = struct( ...
        'num_pose_replacements', 0, ...
        'num_removed_docks', 0, ...
        'num_added_docks', 0, ...
        'num_route_changes', 0, ...
        'num_region_order_changes', 0, ...
        'num_task_assignment_changes', 0, ...
        'coverage_repair_count', 0, ...
        'accepted_iterations', 0, ...
        'rejected_iterations', 0, ...
        'candidate_evaluations', 0, ...
        'route_context_queries', 0, ...
        'cache_hits', 0, ...
        'cache_misses', 0, ...
        'repair_added_docks', 0, ...
        'repair_route_change_count', 0, ...
        'repair_path_delta_m', 0);
    names = fieldnames(defaults);
    for i = 1:numel(names)
        if ~isfield(diagnostics, names{i}) || isempty(diagnostics.(names{i}))
            diagnostics.(names{i}) = defaults.(names{i});
        end
    end
end
